/**
 * 死靈術士【殘酷的誕生】的僕從資料。
 *
 * 官方原文（Bonus Collection p.14，逐字核對）：
 *
 * > 當一個你能看到的屬於野獸、類人、怪物或植物物種的**非反派** NPC 死亡時，
 * > 你可以花費 **2 個墳墓點**，並**減少你自己相當於該 NPC 等級的 HP 和 MP 上限**。
 * > 如果你這樣做，他/她/它的屍體就會變成一個服從你心靈感應命令的僕從：
 * > ·它的物種變成**不死生物**，並接受所有不死生物規則（《核心規則》p305）。
 * >   獲得對暗、光和毒屬性傷害的**新親和力**，失去原先具備的親和力，
 * >   但原物種的其他規則保持不變。
 * > ·它的等級變成**士兵**；如果原來的生物是菁英或冠名，GM 必須相應地減少僕從的 HP 和 MP
 * >   （技能保持不變）。
 * > ·它是個**全新的生物**，擁有滿值的 HP、MP，狀態影響清零重置。它保留原生物的所有裝備。
 * > ·在衝突中，你和僕從會有**各自的回合**，GM 在設計衝突時需要將它算作一個額外的玩家角色。
 * > ·當你休息時，你的僕從也會獲得休息的全部好處。
 * > ·如果僕從的 HP 被降低到 0，並且你距離它超過 **1 個旅行日**，又或者你死亡、失去知覺，
 * >   你的僕從會被立即摧毀。
 * > ·你也可以在任何時候摧毀你的僕從，但在衝突時只能在自己的回合、
 * >   且當下沒有其他效果正在結算時這麼做；如果你想創造一個新的僕從，
 * >   你必須先摧毀當前的那個。
 * > ·如果你的僕從被摧毀，你的 HP 和 MP 上限會恢復正常。
 *
 * ## 為什麼要建這個檔案
 *
 * 這個僕從是**會被反覆引用的子實體**（自己的 HP/MP、裝備、回合），
 * 跟旅人【忠實夥伴】同性質——屬於 `docs/skill-coverage.md` 的 T3（動態狀態），
 * 文字無法承載。它是第六節分析裡唯一需要新元件的一筆。
 *
 * 兩件必須由 App 算、不能靠玩家記的事：
 * 1. **你的 HP/MP 上限懲罰**＝該 NPC 的等級（在 `characterEngine` 的 `addHp`／`addMp` 套用，
 *    僕從被摧毀時自動恢復）。
 * 2. **僕從的 HP 是否歸零**——那是「距離超過 1 個旅行日就會被摧毀」的觸發條件。
 */

/** 新僕從的預設值。 */
export const createDefaultMinion = () => ({
  /** 有沒有活著的僕從。摧毀時設 false，HP/MP 上限的懲罰也一併解除。 */
  active: false,
  /** 僕從的名字（玩家自取）。 */
  name: '',
  /** 原生物的名字，用來對照「它是從誰變來的」。 */
  originName: '',
  /** 原生物的物種（只能是野獸／類人／怪物／植物——官方限定的四種）。 */
  originSpecies: '',
  /**
   * 原生物的等級。這是**你的 HP/MP 上限懲罰**，也是「原本是不是菁英／冠名」的依據。
   * 官方沒有給轉換公式（「GM 必須相應地減少」），所以只記錄原值供 GM 判斷。
   */
  npcLevel: 0,
  /** 原生物的定位：士兵／菁英／冠名。轉換後一律變「士兵」。 */
  originRank: '士兵',
  /** 僕從的當前 HP。滿值＝原生物滿值（官方：「全新的生物，擁有滿值的 HP、MP」）。 */
  currentHp: null,
  /** 僕從的當前 MP。 */
  currentMp: null,
  /** 保留原生物的所有裝備（自由文字）。 */
  equipment: '',
  /** 你的心靈感應命令之類的備註。 */
  notes: '',
});

/** 轉換後一律是不死生物（官方明定）。 */
export const MINION_SPECIES = '不死生物';

/** 轉換後一律是士兵（官方明定：「它的等級變成士兵」）。 */
export const MINION_RANK = '士兵';

/** 官方限定：只有這四種物種的 NPC 可以被轉換。 */
export const CONVERTIBLE_SPECIES = ['野獸', '類人', '怪物', '植物'];

/** 轉換獲得的新親和力（官方明定：暗、光、毒）。 */
export const MINION_AFFINITIES = ['暗', '光', '毒'];

/** 摧毀條件之一：距離超過 1 個旅行日。 */
export const MINION_LEASH_DAYS = 1;
